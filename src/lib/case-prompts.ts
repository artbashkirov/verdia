export function buildCaseAnalysisContext(params: {
  caseDescription?: string;
  documents: Array<{ file_name: string; extracted_text: string; analysis?: Record<string, unknown> }>;
  chatHistory: Array<{ role: string; content: string }>;
  caseType: string;
  lawContext?: string;
  additionalContext?: string;
}): string {
  const parts: string[] = [];

  parts.push(`Тип дела: ${params.caseType === 'objection' ? 'Возражение на иск (позиция ответчика)' : 'Подготовка иска (позиция истца)'}`);

  if (params.caseDescription) {
    parts.push(`\nОписание ситуации от пользователя:\n${params.caseDescription}`);
  }

  if (params.documents.length > 0) {
    parts.push('\nЗагруженные документы:');
    for (const doc of params.documents) {
      parts.push(`\n--- Документ: ${doc.file_name} ---`);
      if (doc.extracted_text) {
        const truncated = doc.extracted_text.length > 5000
          ? doc.extracted_text.substring(0, 5000) + '\n[...текст обрезан...]'
          : doc.extracted_text;
        parts.push(truncated);
      } else {
        parts.push('[Текст не удалось извлечь]');
      }
    }
  }

  if (params.chatHistory.length > 0) {
    parts.push('\nИстория общения по делу:');
    for (const msg of params.chatHistory.slice(-10)) {
      const role = msg.role === 'user' ? 'Пользователь' : 'Помощник';
      parts.push(`${role}: ${msg.content}`);
    }
  }

  if (params.lawContext) {
    parts.push(`\nРелевантные нормы права:\n${params.lawContext}`);
  }

  if (params.additionalContext) {
    parts.push(params.additionalContext);
  }

  return parts.join('\n');
}
