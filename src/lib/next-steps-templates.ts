/**
 * Шаблоны "Что делать дальше" по типам документов.
 *
 * Используются после генерации документа и согласия пользователя
 * получить инструкцию. Гибрид: статический шаблон + AI-секция
 * с цитатами из RAG (см. `src/app/api/chat/route.ts`).
 */

export type DocumentType =
  | 'pretenziya'
  | 'iskovoe'
  | 'hodatajstvo'
  | 'vozrazhenie'
  | 'unknown';

/**
 * Маркер вопроса в сообщении ассистента, по которому потом распознаём,
 * что пользователь отвечает именно на этот follow-up.
 * Должен быть стабильным и не пересекаться с обычным контентом.
 */
export const NEXT_STEPS_QUESTION_MARKER = /что делать дальше с (этим документом|этими документами)\?/i;

/**
 * Сама фраза follow-up вопроса, которая отправляется пользователю.
 */
export function buildNextStepsQuestion(documentsCount: number): string {
  return documentsCount > 1
    ? 'Хотите, расскажу, что делать дальше с этими документами?'
    : 'Хотите, расскажу, что делать дальше с этим документом?';
}

/**
 * Определяет тип документа по его заголовку (поле `title` в documents JSON).
 * Заголовки приходят от AI на русском, поэтому матчим по корням слов.
 */
export function detectDocumentType(title: string): DocumentType {
  if (!title) return 'unknown';
  const t = title.toLowerCase();

  if (/возражени/.test(t)) return 'vozrazhenie';
  if (/претензи/.test(t)) return 'pretenziya';
  if (/ходатайств/.test(t)) return 'hodatajstvo';
  if (/исков|^иск\b|искового заявления/.test(t)) return 'iskovoe';

  return 'unknown';
}

