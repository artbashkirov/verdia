/**
 * Возвращает шаблон шагов для одного типа документа.
 */
export function getNextStepsTemplate(type: DocumentType): string {
  return TEMPLATES[type] ?? TEMPLATES.unknown;
}

/**
 * Собирает финальный шаблонный блок для набора документов.
 * Если все документы одного типа — один блок.
 * Если разные типы — несколько блоков, разделённых пустой строкой.
 */
export function buildTemplateBlock(documentTitles: string[]): string {
  const types = documentTitles
    .map(detectDocumentType)
    .filter((t, i, arr) => arr.indexOf(t) === i); // unique, сохраняем порядок

  if (types.length === 0) {
    return getNextStepsTemplate('unknown');
  }

  return types.map(getNextStepsTemplate).join('\n\n');
}
